#!/bin/bash
# Switch the RTC sync backend for benchmarking.
#
# Usage:
#   ./tools/rtc-bench/switch-backend.sh <storage> [endpoint]
#
# Storage options:  post-meta (default), object-cache, custom-table
# Endpoint options: rest-api (default), lightweight
#
# Examples:
#   ./tools/rtc-bench/switch-backend.sh post-meta rest-api      # Default
#   ./tools/rtc-bench/switch-backend.sh custom-table rest-api    # Custom table + REST
#   ./tools/rtc-bench/switch-backend.sh custom-table lightweight # Custom table + lightweight
#   ./tools/rtc-bench/switch-backend.sh object-cache lightweight # Object cache + lightweight

STORAGE="${1:-post-meta}"
ENDPOINT="${2:-rest-api}"

echo "Switching to: storage=$STORAGE, endpoint=$ENDPOINT"

PHP_CODE="<?php
// RTC Sync Backend Switcher (auto-generated by rtc-bench)
add_filter('wp_sync_storage_backend', function() { return '${STORAGE}'; });
add_filter('wp_sync_endpoint_type', function() { return '${ENDPOINT}'; });
"

npx wp-env run cli -- bash -c "cat > /var/www/html/wp-content/mu-plugins/rtc-bench-backend.php << 'MUEOF'
${PHP_CODE}
MUEOF"

echo "Done. Active config:"
npx wp-env run cli -- wp eval "
\$storage = apply_filters('wp_sync_storage_backend', 'post-meta');
\$endpoint = apply_filters('wp_sync_endpoint_type', 'rest-api');
echo \"  Storage:  \$storage\n\";
echo \"  Endpoint: \$endpoint\n\";
"
